import { describe, expect, it } from 'vitest';
import { PgmError, assertDigest, assertDims, parsePgm, sha256Hex } from '../src/map/pgm';

const ascii = (text: string) => new TextEncoder().encode(text);
const header = (values: (string | number)[]) => ascii(`P5\n${values.join('\n')}\n`);

describe('PGM raster decoding', () => {
  it('reads binary P5 pixels with row 0 as the image top', () => {
    const bytes = new Uint8Array([...header([2, 2, 255]), 0, 64, 128, 255]);
    const raster = parsePgm(bytes);
    expect(raster).toMatchObject({ magic: 'P5', width: 2, height: 2, maxval: 255 });
    expect([...raster.gray]).toEqual([0, 64, 128, 255]);
  });
  it('scales low maxval binary maps to full grey', () => {
    const raster = parsePgm(new Uint8Array([...header([2, 1, 3]), 0, 3]));
    expect([...raster.gray]).toEqual([0, 255]);
  });
  it('reads plain P2 values and skips comments', () => {
    const raster = parsePgm(ascii('P2\n# generated by map_server\n2 2\n255\n0 128\n255 20\n'));
    expect(raster).toMatchObject({ magic: 'P2', width: 2, height: 2 });
    expect([...raster.gray]).toEqual([0, 128, 255, 20]);
  });
  it('rejects other pixel formats instead of guessing a layout', () => {
    for (const magic of ['P1', 'P4', 'P6', 'P7']) {
      const bytes = ascii(`${magic}\n1 1\n255\n`);
      expect(() => parsePgm(bytes)).toThrow(PgmError);
      try { parsePgm(bytes); } catch (error) { expect((error as PgmError).code).toBe('unsupported_magic'); }
    }
  });
  it('reports truncated pixels and bad geometry explicitly', () => {
    expect(() => parsePgm(new Uint8Array([...header([4, 4, 255]), 1, 2, 3]))).toThrowError(/像素字节不足/);
    expect(() => parsePgm(new Uint8Array([...header([0, 2, 255])]))).toThrowError(/栅格尺寸无效/);
    expect(() => parsePgm(ascii('P5\n2 2\n0\n'))).toThrowError(/maxval 无效/);
    expect(() => parsePgm(ascii('P5\n2 2\n65535\n'))).toThrow(PgmError);
    expect(() => parsePgm(ascii('P2\n2 1\n255\n999999 1\n'))).toThrowError(/超过 maxval/);
  });
  it('checks digest and declared dimensions separately', async () => {
    const bytes = new Uint8Array([...header([1, 1, 255]), 7]);
    const digest = await sha256Hex(bytes);
    expect(digest).toHaveLength(64);
    expect(() => assertDigest(digest, digest.toUpperCase())).not.toThrow();
    expect(() => assertDigest(digest, 'f'.repeat(64))).toThrowError(/图像摘要不符/);
    const raster = parsePgm(bytes);
    expect(() => assertDims(raster, 1, 1)).not.toThrow();
    expect(() => assertDims(raster, 59, 47)).toThrowError(/栅格尺寸不符/);
  });
});
